library(tidyverse)

# -------------------------------------------------------------------------
# STEP 1: DATA INGESTION AND QUALITY ASSURANCE
# -------------------------------------------------------------------------

raw_tracker <- read_csv("C:/Users/DELL/Desktop/R_project/western_data.csv")

# Diagnostic structural check
print(paste("Observations:", nrow(raw_tracker), "| Variables:", ncol(raw_tracker)))
glimpse(raw_tracker)

# -------------------------------------------------------------------------
# STEP 2: CLASS HARMONIZATION AND COERCION
# -------------------------------------------------------------------------

cleaned_tracker <- raw_tracker %>%
  mutate(
    rainfall_mm       = as.numeric(RF),
    humidity_pct      = as.numeric(RH),
    max_temp_c        = as.numeric(MXT),
    min_temp_c        = as.numeric(MNT),
    cases_region_1    = as.numeric(malaria_cases_W_1),
    cases_region_2    = as.numeric(malaria_cases_W_2)
  ) %>%
  mutate(
    mean_temp_c       = (max_temp_c + min_temp_c) / 2,
    grand_total_cases = cases_region_1 + cases_region_2,
    month_id          = row_number()
  )

# Verify structural alignments
cleaned_tracker %>% 
  select(rainfall_mm, mean_temp_c, grand_total_cases, month_id) %>% 
  summary()

# -------------------------------------------------------------------------
# STEP 3: FEATURE ENGINEERING AND HARMONIC FOURIER BALANCING
# -------------------------------------------------------------------------

# Segmented counter milestones for Interrupted Time Series (ITS) 
# Note: Massive intervention deployment executed at Month 60 (December 2015)
replication_features <- cleaned_tracker %>%
  mutate(
    time_index          = month_id,
    intervention_status = ifelse(time_index > 60, 1, 0),
    post_slope          = ifelse(time_index > 60, time_index - 60, 0),
    
    # 12-month cyclical Fourier waves for structural seasonality control
    sin_12              = sin(2 * pi * month_id / 12),
    cos_12              = cos(2 * pi * month_id / 12)
  )

# -------------------------------------------------------------------------
# STEP 4: MECHANISTIC HYDROMETEOROLOGICAL EMULATION
# -------------------------------------------------------------------------

vectri_replicated_data <- replication_features %>%
  mutate(
    # Ephemeral breeding pool surface fraction approximation
    simulated_pool_area = (rainfall_mm * 0.05) * (humidity_pct / 100),
    
    # Extrinsic Incubation Period (EIP) degree-day parameters above an 18°C baseline
    parasite_incubation_days = ifelse(mean_temp_c > 18, 111 / (mean_temp_c - 18), NA),
    
    # Gonotrophic cycle frequency function representing biting rate acceleration
    mosquito_biting_rate = ifelse(mean_temp_c > 9.9, (mean_temp_c - 9.9) / 36.5, 0)
  )

# -------------------------------------------------------------------------
# STEP 5: ECO-BIOLOGICAL LAG ENGINEERING
# -------------------------------------------------------------------------

replication_lagged_features <- vectri_replicated_data %>%
  mutate(
    pool_area_lag1   = lag(simulated_pool_area, 1),
    pool_area_lag2   = lag(simulated_pool_area, 2),
    biting_rate_lag1 = lag(mosquito_biting_rate, 1)
  ) %>%
  # Strip out empty alignment lines generated by the temporal time shifts
  filter(!is.na(pool_area_lag2) & !is.na(grand_total_cases))

# -------------------------------------------------------------------------
# STEP 6: MODEL EXECUTION AND CROSS-VALIDATION STATS
# -------------------------------------------------------------------------

# Model A: Baseline ITS Regression
its_model <- lm(grand_total_cases ~ time_index + intervention_status + post_slope + 
                  rainfall_mm + mean_temp_c + humidity_pct + sin_12 + cos_12, 
                data = replication_lagged_features)
summary(its_model)

# Model B: Calibrated Lag-Phased Mechanistic Framework
calibrated_lag_model <- lm(grand_total_cases ~ pool_area_lag2 + biting_rate_lag1 + 
                             intervention_status + sin_12 + cos_12, 
                           data = replication_lagged_features)
summary(calibrated_lag_model)

# Performance diagnostics
pool_correlation <- cor(replication_lagged_features$pool_area_lag2, 
                        replication_lagged_features$grand_total_cases, method = "pearson")
model_residuals  <- residuals(calibrated_lag_model)
replication_rmse <- sqrt(mean(model_residuals^2))

cat("\n--- PERFORMANCE VALIDATION REPORT ---\n",
    "2-Month Lagged Hydrology Correlation (r):", round(pool_correlation, 4), "\n",
    "Model Absolute Error (RMSE):", round(replication_rmse, 2), "\n",
    "Model Explanatory Variance (Adj R2):", round(summary(calibrated_lag_model)$adj.r.squared, 4), "\n")

# -------------------------------------------------------------------------
# STEP 7: MATRIX MATRIX EXPORT TO DESKTOP
# -------------------------------------------------------------------------

replication_matrix <- as.data.frame(summary(calibrated_lag_model)$coefficients) %>%
  rownames_to_column(var = "Epidemiological_Indicator") %>%
  rename(
    Beta_Estimate    = Estimate,
    Standard_Error   = `Std. Error`,
    T_Statistic      = `t value`,
    P_Value          = `Pr(>|t|)`
  ) %>%
  mutate(across(where(is.numeric), ~ round(., 4)))

write_csv(replication_matrix, "C:/Users/DELL/Desktop/malaria_model_parameter_matrix.csv")
